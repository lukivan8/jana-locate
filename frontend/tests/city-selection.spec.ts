for (const width of [1440, 390]) {
  test(`unique settlement is resolved without a choice at ${width}px`, async ({ page, context }) => {
    await page.setViewportSize({ width, height: width === 390 ? 844 : 1000 })
    const api = process.env.JANA_TEST_API_URL ?? 'http://localhost:8080'
    await context.route('**/config.js', route => route.fulfill({ contentType: 'text/javascript', body: `window.JANA_CONFIG = ${JSON.stringify({ apiBaseUrl: api })}` }))
    const selections: string[] = []
    page.on('request', request => {
      if (request.method() === 'POST' && request.url().endsWith('/selections')) selections.push(request.url())
    })
    await page.goto('/')
    await page.getByLabel('Один адрес на строку').fill('Сарань, улица Жамбыла 63')
    await page.getByRole('button', { name: 'Нормализовать пакет', exact: true }).click()
    const picker = page.getByRole('region', { name: 'Населённый пункт по справочнику', exact: true })
    await expect(picker).toContainText('Сарань · город')
    await expect(picker).toContainText('Карагандинская область')
    await expect(picker.getByRole('radio')).toHaveCount(0)
    await expect(picker.getByRole('button')).toHaveCount(0)
    await expect(page.getByLabel('Область', { exact: true })).toHaveValue('Карагандинская область')
    await expect(page.getByLabel('Город', { exact: true })).toHaveValue('Сарань')
    // Opening a unique match must not re-normalize or overwrite operator corrections.
    await page.getByLabel('Квартира', { exact: true }).fill('99')
    await page.getByRole('button', { name: 'Сохранить исправления', exact: true }).click()
    await page.reload()
    await expect(page.locator('tbody > tr').first().getByRole('button')).toHaveAttribute('aria-expanded', 'true')
    await expect(picker).toContainText('Сарань · город')
    await expect(picker.getByRole('button')).toHaveCount(0)
    await expect(page.getByLabel('Квартира', { exact: true })).toHaveValue('99')
    expect(selections).toHaveLength(0)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  })
}
