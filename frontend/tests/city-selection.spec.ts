import { test, expect } from '@playwright/test'

for (const width of [1440, 390]) {
  test(`settlement choices restore hierarchy without confirming a building at ${width}px`, async ({ page, context }) => {
    await page.setViewportSize({ width, height: width === 390 ? 844 : 1000 })
    const api = process.env.JANA_TEST_API_URL ?? 'http://localhost:8080'
    await context.route('**/config.js', route => route.fulfill({ contentType: 'text/javascript', body: `window.JANA_CONFIG = ${JSON.stringify({ apiBaseUrl: api })}` }))
    const raw = '  Караганда, улица Алалыкина 999999  '
    await page.goto('/')
    await page.getByLabel('Загрузить JSON').setInputFiles({ name: 'cities.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify([{ id: 'duplicate', raw_address: raw }, { id: 'duplicate', raw_address: 'Караганда' }])) })
    await page.getByRole('button', { name: 'Нормализовать пакет', exact: true }).click()
    await expect(page.locator('tbody tr')).toHaveCount(2)
    const jobURL = page.url()
    await page.locator('tbody tr').first().getByRole('button').click()
    await expect(page.locator('tbody > tr').nth(1).getByRole('region', { name: 'Исправление адреса', exact: true })).toBeVisible()
    await expect(page.locator('tbody > tr').first().getByRole('button')).toHaveAttribute('aria-expanded', 'true')
    const picker = page.getByRole('region', { name: 'Населённый пункт по справочнику', exact: true })
    await expect(picker.getByRole('radio')).toHaveCount(2)
    await expect(picker.getByRole('radio', { name: /Караганда · город.*Карагандинская область/ })).toBeVisible()
    await expect(picker.getByRole('radio', { name: /Караганда · село.*Актюбинская область/ })).toBeVisible()
    const other = await context.newPage()
    await other.goto(jobURL)
    await expect(other.locator('tbody tr')).toHaveCount(2)
    await other.locator('tbody tr').first().getByRole('button').click()
    await other.getByRole('radio', { name: /Караганда · село/ }).check()
    await picker.getByRole('radio', { name: /Караганда · город/ }).check()
    await picker.getByRole('button', { name: 'Выбрать населённый пункт', exact: true }).click()
    await expect(picker.getByRole('radio')).toHaveCount(0)
    await expect(picker).toContainText('Карагандинская область')
    await expect(picker.getByRole('button', { name: 'Исправить', exact: true })).toBeVisible()
    await expect(page.getByLabel('Область', { exact: true })).toHaveValue('Карагандинская область')
    await expect(page.getByLabel('Широта', { exact: true })).toHaveCount(0)
    await expect(page.getByLabel('Район', { exact: true })).toHaveValue('')
    await expect(page.locator('tbody tr').getByRole('img', { name: 'Проверено оператором', exact: true })).toHaveCount(0)
    await other.getByRole('button', { name: 'Выбрать населённый пункт', exact: true }).click()
    await expect(other.getByRole('alert')).toContainText('Задание изменилось')
    await other.close()
    await page.reload()
    await expect(page.locator('tbody tr')).toHaveCount(2)
    await page.locator('tbody tr').first().getByRole('button').click()
    await expect(picker.getByRole('radio')).toHaveCount(0)
    await picker.getByRole('button', { name: 'Исправить', exact: true }).click()
    await expect(page.getByRole('radio', { name: /Караганда · город/ })).toBeChecked()
    await page.getByRole('radio', { name: /Караганда · село/ }).check()
    await page.getByRole('button', { name: 'Выбрать населённый пункт', exact: true }).click()
    await expect(page.getByLabel('Область', { exact: true })).toHaveValue('Актюбинская область')
    await expect(page.getByLabel('Широта', { exact: true })).toHaveCount(0)
    await page.getByRole('button', { name: 'Свернуть', exact: true }).click()
    const downloadPromise = page.waitForEvent('download')
    await page.getByRole('button', { name: 'Экспорт JSON', exact: true }).click()
    const stream = await (await downloadPromise).createReadStream()
    const chunks: Buffer[] = []; for await (const chunk of stream!) chunks.push(chunk)
    const { results } = JSON.parse(Buffer.concat(chunks).toString())
    expect(results.map((r: { id: string }) => r.id)).toEqual(['duplicate', 'duplicate'])
    expect(results[0].raw_address).toBe(raw)
    expect(results[0].province).toBe('Актюбинская область')
    expect(results[0].coordinates).toBeNull()
    expect(results[1].province).toBeNull()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  })
}

