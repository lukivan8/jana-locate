import { test, expect } from '@playwright/test'

for (const viewport of [{ width: 1440, height: 1000 }, { width: 390, height: 844 }]) {
  test(`saved corrections restore and reject another tab at ${viewport.width}px`, async ({ page, context }) => {
    await page.setViewportSize(viewport)
    const api = process.env.JANA_TEST_API_URL ?? 'http://localhost:8080'
    await context.route('**/config.js', route => route.fulfill({ contentType: 'text/javascript', body: `window.JANA_CONFIG = ${JSON.stringify({ apiBaseUrl: api })}` }))
    await page.goto('/')
    const raw = '  Совсем неизвестный адрес\nс переносом  '
    await page.getByLabel('Загрузить JSON').setInputFiles({ name: 'review.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify([{ id: 'duplicate', raw_address: raw }, { id: 'duplicate', raw_address: '' }])) })
    await page.getByRole('button', { name: 'Нормализовать пакет', exact: true }).click()
    await expect(page.locator('tbody tr')).toHaveCount(2)
    const jobURL = page.url()
    expect(new URL(jobURL).searchParams.get('job')).toBeTruthy()
    const other = await context.newPage()
    await other.goto(jobURL)
    await expect(other.locator('tbody tr')).toHaveCount(2)
    await other.locator('tbody tr').first().getByRole('button').click()
    await other.getByLabel('Квартира', { exact: true }).fill('старое изменение')
    await page.locator('tbody tr').first().getByRole('button').click()
    await page.getByLabel('Квартира', { exact: true }).fill('77')
    await page.getByLabel('Подъезд', { exact: true }).fill('3')
    await page.getByRole('button', { name: 'Сохранить исправления', exact: true }).click()
    await expect(page.getByRole('button', { name: 'Сохранить исправления', exact: true })).toHaveCount(0)
    await other.getByRole('button', { name: 'Сохранить исправления', exact: true }).click()
    await expect(other.getByRole('alert')).toContainText('Задание изменилось')
    await expect(other.getByLabel('Квартира', { exact: true })).toHaveValue('старое изменение')
    await other.close()
    // Save a different record without re-normalizing or replacing the first correction.
    await page.locator('tbody tr').last().getByRole('button').click()
    await page.getByLabel('Ориентир', { exact: true }).fill('Проверено: вход со двора')
    await page.getByRole('button', { name: 'Сохранить исправления', exact: true }).click()
    await expect(page.getByRole('button', { name: 'Сохранить исправления', exact: true })).toHaveCount(0)
    await page.reload()
    await expect(page.locator('tbody tr')).toHaveCount(2)
    await expect(page.locator('tbody tr').getByRole('img', { name: 'Проверено оператором', exact: true })).toHaveCount(2)
    await page.locator('tbody tr').first().getByRole('button').click()
    await expect(page.getByLabel('Квартира', { exact: true })).toHaveValue('77')
    await expect(page.getByLabel('Подъезд', { exact: true })).toHaveValue('3')
    await expect(page.getByLabel('Широта', { exact: true })).toHaveCount(0)
    await page.getByRole('button', { name: 'Свернуть', exact: true }).click()
    const downloadPromise = page.waitForEvent('download')
    await page.getByRole('button', { name: 'Экспорт JSON', exact: true }).click()
    const stream = await (await downloadPromise).createReadStream()
    const chunks: Buffer[] = []; for await (const chunk of stream!) chunks.push(chunk)
    const { results } = JSON.parse(Buffer.concat(chunks).toString())
    expect(results.map((r: { id: string }) => r.id)).toEqual(['duplicate', 'duplicate'])
    expect(results[0].raw_address).toBe(raw)
    expect(results[0].apartment).toBe('77')
    expect(results[0].coordinates).toBeNull()
    expect(results[1].landmark).toBe('Проверено: вход со двора')
    await page.getByLabel('Только требующие проверки').check()
    await expect(page.locator('tbody tr')).toHaveCount(0)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  })
}
