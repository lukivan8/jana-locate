import { test, expect } from '@playwright/test'

test('normalization, field correction, restore and export do not require geocoding', async ({ page }) => {
  const api = process.env.JANA_TEST_API_URL ?? 'http://localhost:8080'
  await page.route('**/config.js', route => route.fulfill({ contentType: 'text/javascript', body: `window.JANA_CONFIG = ${JSON.stringify({ apiBaseUrl: api })}` }))
  await page.goto('/')
  await page.getByLabel('Один адрес на строку').fill('Карагандинская область, город Сарань, улица Жамбыла 63 кв 21\nНеизвестный адрес')
  await page.getByRole('button', { name: 'Нормализовать пакет' }).click()
  await expect(page.locator('tbody tr')).toHaveCount(2)
  await expect(page.locator('tbody tr').first().getByRole('img', { name: 'Нормализован', exact: true })).toBeVisible()
  await page.locator('tbody tr').first().getByRole('button').click()
  await expect(page.getByLabel('Широта', { exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Подтвердить здание и сохранить' })).toHaveCount(0)
  await page.getByLabel('Квартира', { exact: true }).fill('99')
  await page.getByRole('button', { name: 'Сохранить исправления', exact: true }).click()
  await expect(page.locator('tbody tr').first().getByRole('img', { name: 'Проверено оператором', exact: true })).toBeVisible()
  await expect(page.getByText('Исправления сохранены', { exact: false })).toHaveCount(0)
  await page.reload()
  await expect(page.locator('tbody tr')).toHaveCount(2)
  await page.locator('tbody tr').first().getByRole('button').click()
  await expect(page.getByLabel('Квартира', { exact: true })).toHaveValue('99')
  await page.getByRole('button', { name: 'Свернуть', exact: true }).click()
  await page.getByLabel('Только требующие проверки').check()
  await expect(page.locator('tbody tr')).toHaveCount(1)
  await page.getByLabel('Только требующие проверки').uncheck()
  const downloading = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Экспорт JSON' }).click()
  const stream = await (await downloading).createReadStream()
  const chunks = []; for await (const chunk of stream!) chunks.push(chunk)
  const result = JSON.parse(Buffer.concat(chunks).toString()).results[0]
  expect(result.apartment).toBe('99')
  expect(result.coordinates).toBeNull()
  expect(result.catalog_id).toBeNull()
  expect(result.status).toBe('matched')
  expect(result.warnings).not.toContain('coordinates_unknown')
  expect(result.warnings).not.toContain('gliner_unavailable')
})
