import { test, expect } from '@playwright/test'

for (const viewport of [{ width: 1440, height: 1000 }, { width: 390, height: 844 }]) {
  test(`address wizard imports, edits and opens one result at ${viewport.width}px`, async ({ page }) => {
    await page.setViewportSize(viewport)
    const api = process.env.JANA_TEST_API_URL ?? 'http://localhost:8080'
    await page.route('**/config.js', route => route.fulfill({ contentType: 'text/javascript', body: `window.JANA_CONFIG = ${JSON.stringify({ apiBaseUrl: api })}` }))
    await page.goto('/')
    const input = page.getByLabel('Один адрес на строку')
    const file = page.getByLabel('Загрузить JSON, TXT, CSV или XLSX')
    await expect(input).toHaveValue('')
    await expect(page.getByRole('button', { name: 'Сбросить', exact: true })).toHaveCount(0)
    await expect(page.getByRole('heading', { name: 'Очередь проверки' })).toHaveCount(0)
    await expect(page.getByRole('button', { name: 'Нормализовать пакет' })).toBeDisabled()
    await file.setInputFiles({ name: 'addresses.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify({ records: [{ id: 'original-id', raw_address: 'Сарань, улица Жамбыла 63' }] })) })
    await expect(input).toHaveValue('Сарань, улица Жамбыла 63')
    await expect(input).toBeEditable()
    await expect(page.getByRole('button', { name: 'Сбросить', exact: true })).toHaveCount(0)
    await expect(page.getByRole('heading', { name: 'Сохранённые задания' })).toHaveCount(0)
    await expect(page.getByText('Форматы файлов', { exact: true })).toHaveCount(0)
    await expect(page.getByText('Исследовать тестовые примеры', { exact: true })).toHaveCount(0)
    await expect(page.getByRole('button', { name: 'На весь экран' }).locator('svg')).toHaveCount(1)
    await expect(page.locator('tbody tr')).toHaveCount(0)
    await page.getByRole('button', { name: 'На весь экран' }).click()
    await expect(page.getByRole('dialog')).toHaveJSProperty('open', true)
    expect(await page.getByRole('dialog').evaluate(el => el.matches(':modal'))).toBe(true)
    await input.fill('Сарань, улица Жамбыла 63 кв 42')
    await page.keyboard.press('Escape')
    await expect(page.getByRole('button', { name: 'На весь экран' })).toBeFocused()
    await expect(input).toHaveValue('Сарань, улица Жамбыла 63 кв 42')
    const request = page.waitForRequest(r => r.url().endsWith('/v1/normalization-jobs') && r.method() === 'POST')
    await page.getByRole('button', { name: 'Нормализовать пакет' }).click()
    expect((await request).postDataJSON()).toEqual({ records: [{ id: 'original-id', raw_address: 'Сарань, улица Жамбыла 63 кв 42' }] })
    await expect(page.getByRole('heading', { name: 'Сарань, улица Жамбыла 63 кв 42', exact: true })).toBeVisible()
    await expect(page.getByLabel('Квартира', { exact: true })).toHaveValue('42')
    await page.getByRole('button', { name: 'Сбросить', exact: true }).click()
    await expect(input).toHaveValue('')
    await file.setInputFiles({ name: 'addresses.csv', mimeType: 'text/csv', buffer: Buffer.from('id,raw_address\r\nfirst,"Караганда, Алалыкина 12"\r\nsecond,"Сарань, Жамбыла 63"') })
    await expect(page.getByRole('dialog', { name: 'Выберите колонку с адресами' })).toBeVisible()
    await page.getByRole('button', { name: 'Импортировать', exact: true }).click()
    await expect(input).toHaveValue('Караганда, Алалыкина 12\nСарань, Жамбыла 63')
    await file.setInputFiles({ name: 'bad.json', mimeType: 'application/json', buffer: Buffer.from('{broken') })
    await expect(page.getByRole('alert')).toContainText('Некорректный JSON')
    await expect(input).toHaveValue('Караганда, Алалыкина 12\nСарань, Жамбыла 63')
    await file.setInputFiles({ name: 'addresses.txt', mimeType: 'text/plain', buffer: Buffer.from('Караганда, Алалыкина 12\r\nСарань, Жамбыла 63') })
    await expect(input).toHaveValue('Караганда, Алалыкина 12\nСарань, Жамбыла 63')
    await page.getByRole('button', { name: 'Нормализовать пакет' }).click()
    await expect(page.locator('tbody tr')).toHaveCount(2)
    await expect(page.getByRole('heading', { name: 'Сарань, улица Жамбыла 63 кв 42', exact: true })).toHaveCount(0)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  })
}
