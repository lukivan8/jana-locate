import { argbFromHex, hexFromArgb, themeFromSourceColor } from '@material/material-color-utilities'
import { writeFileSync } from 'node:fs'

// Build-time only: the app never fetches a palette or loads this library at runtime.
const theme = themeFromSourceColor(argbFromHex('#147c58'))
const kebab = name => name.replace(/[A-Z]/g, c => `-${c.toLowerCase()}`)
function scheme(dark) {
  const roles = theme.schemes[dark ? 'dark' : 'light'].toJSON()
  const neutral = theme.palettes.neutral
  const surfaces = dark
    ? { surface: 6, surfaceDim: 6, surfaceBright: 24, surfaceContainerLowest: 4, surfaceContainerLow: 10, surfaceContainer: 12, surfaceContainerHigh: 17, surfaceContainerHighest: 22 }
    : { surface: 98, surfaceDim: 87, surfaceBright: 98, surfaceContainerLowest: 100, surfaceContainerLow: 96, surfaceContainer: 94, surfaceContainerHigh: 92, surfaceContainerHighest: 90 }
  for (const [name, tone] of Object.entries(surfaces)) roles[name] = neutral.tone(tone)
  return Object.entries(roles).map(([name, value]) => `  --md-sys-color-${kebab(name)}: ${hexFromArgb(value)};`).join('\n')
}
writeFileSync(new URL('../src/ui/colors.css', import.meta.url), `/* Generated by npm run theme:generate. Seed: #147c58. Do not hand edit. */\n:root {\n  color-scheme: light;\n${scheme(false)}\n}\n@media (prefers-color-scheme: dark) {\n  :root {\n    color-scheme: dark;\n${scheme(true)}\n  }\n}\n`)
