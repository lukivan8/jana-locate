import { argbFromHex, hexFromArgb, themeFromSourceColor } from '@material/material-color-utilities'
import { writeFileSync } from 'node:fs'

// Build-time only: the app never fetches a palette or loads this library at runtime.
// Exact Jana Post brand color supplied by the user (RGB 17, 125, 1).
const brandSeed = '#117d01'
const theme = themeFromSourceColor(argbFromHex(brandSeed))
const kebab = name => name.replace(/[A-Z]/g, c => `-${c.toLowerCase()}`)
function scheme() {
  const roles = theme.schemes.light.toJSON()
  // Preserve the approved brand color instead of M3's default primary tone.
  // White on this green passes WCAG AA for normal text.
  roles.primary = argbFromHex(brandSeed)
  roles.onPrimary = argbFromHex('#ffffff')
  // Semantic amber roles for operator attention, separate from brand and error.
  const warning = themeFromSourceColor(argbFromHex('#f9a825')).palettes.primary
  roles.warning = warning.tone(40)
  roles.warningContainer = warning.tone(90)
  roles.onWarningContainer = warning.tone(10)
  const neutral = theme.palettes.neutral
  const surfaces = { surface: 98, surfaceDim: 87, surfaceBright: 98, surfaceContainerLowest: 100, surfaceContainerLow: 96, surfaceContainer: 94, surfaceContainerHigh: 92, surfaceContainerHighest: 90 }
  for (const [name, tone] of Object.entries(surfaces)) roles[name] = neutral.tone(tone)
  return Object.entries(roles).map(([name, value]) => `  --md-sys-color-${kebab(name)}: ${hexFromArgb(value)};`).join('\n')
}
writeFileSync(new URL('../src/ui/colors.css', import.meta.url), `/* Generated by npm run theme:generate. Seed: ${brandSeed}. Do not hand edit. */\n:root {\n  color-scheme: light;\n${scheme()}\n}\n`)
