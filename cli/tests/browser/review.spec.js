async function emptyWorkspace(page) {
  const { runs }=await (await page.request.get('/v1/runs')).json();
  const current=runs.find(run=>run.status!=='published');
  await page.goto(current ? `/?run=${current.id}` : '/');
  await expect(page).toHaveURL(/[?&](job|run)=/);
  await expect(page.getByRole('button',{name:'Сбросить',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Сбросить',exact:true}).click();
  await expect(page.getByLabel('Один адрес на строку')).toHaveValue('');
}
