#!/usr/bin/env python3
"""Generate a standalone synthetic PostgreSQL seed from an explicitly supplied dataset."""
import argparse
from datetime import date, timedelta
import hashlib
import json
from pathlib import Path
import random


def literal(value: str) -> str:
    if '\0' in value:
        raise ValueError('PostgreSQL text cannot contain NUL')
    return "'" + value.replace("'", "''") + "'"


def generate(source: Path, output: Path, seed: int) -> None:
    source_bytes = source.read_bytes()
    dataset = json.loads(source_bytes)
    records = dataset['records']
    if not records or any(not isinstance(r.get('id'), str) or not isinstance(r.get('raw_address'), str) for r in records):
        raise ValueError('Expected nonempty records: [{id: string, raw_address: string}]')
    if len({r['id'] for r in records}) != len(records):
        raise ValueError('Dataset IDs must be unique')
    rng = random.Random(seed)
    first_names = ['Айдана', 'Алия', 'Амина', 'Анастасия', 'Аружан', 'Асель', 'Виктория', 'Дана', 'Диана', 'Екатерина', 'Айдар', 'Александр', 'Алихан', 'Артём', 'Арман', 'Данияр', 'Дмитрий', 'Ерлан', 'Марат', 'Тимур']
    last_names = ['Абдрахман', 'Алим', 'Ахмет', 'Бек', 'Иса', 'Карим', 'Ким', 'Ли', 'Нур', 'Омар', 'Пак', 'Рахим', 'Садык', 'Серик', 'Султан', 'Толеу', 'Хан', 'Шарип']
    start, end = date(2025, 1, 1), date(2026, 10, 15)
    rows = []
    for index, record in enumerate(records, 1):
        name = f'{rng.choice(first_names)} {rng.choice(last_names)}'
        ordered = start + timedelta(days=rng.randrange((end - start).days + 1))
        address = rng.choice(records)['raw_address']
        values = [str(index), literal(record['id']), literal(name), literal(ordered.isoformat()), literal(address), literal(record['raw_address'])]
        rows.append('  (' + ', '.join(values) + ')')
    sql = f'''-- GENERATED SYNTHETIC EXAMPLE: not real orders, customers or verified addresses.
-- Input: address-anomalies.json; SHA-256: {hashlib.sha256(source_bytes).hexdigest()}
-- Random seed: {seed}; rows: {len(records)}; source ID is retained in anomaly_id.
-- Public source components: © OpenStreetMap contributors, ODbL-1.0.
-- https://www.openstreetmap.org/copyright
-- Delivery address strings are preserved exactly; no normalization answers included.
BEGIN;
SET standard_conforming_strings = on;
CREATE TABLE public.orders (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  anomaly_id text NOT NULL UNIQUE,
  name text NOT NULL,
  order_date date NOT NULL,
  address text NOT NULL,
  delivery_address text NOT NULL
);
COMMENT ON TABLE public.orders IS 'SYNTHETIC orders from address-anomalies.json. Names/dates are fictional; addresses are unverified synthetic mutations of public OSM components. © OpenStreetMap contributors, ODbL-1.0: https://www.openstreetmap.org/copyright';
COMMENT ON COLUMN public.orders.anomaly_id IS 'Original address-anomalies.json record ID for traceability; not a normalization answer';
COMMENT ON COLUMN public.orders.address IS 'Synthetic customer address randomly sampled from the same unverified dataset';
COMMENT ON COLUMN public.orders.delivery_address IS 'Exact raw_address from the corresponding anomaly example; intended normalization input';
INSERT INTO public.orders (id, anomaly_id, name, order_date, address, delivery_address) VALUES
''' + ',\n'.join(rows) + ''';
SELECT setval(pg_get_serial_sequence('public.orders', 'id'), (SELECT max(id) FROM public.orders));
COMMIT;
'''
    output.write_text(sql, encoding='utf-8')
    print(f'Generated {len(records)} synthetic orders → {output}')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path, required=True)
    parser.add_argument('--output', type=Path, default=Path(__file__).with_name('seed.sql'))
    parser.add_argument('--seed', type=int, default=20261016)
    args = parser.parse_args()
    generate(args.source, args.output, args.seed)
